"""The private data pack (../Signpost_Data): source layers, the merged tables, _meta.lua, the TOC and the gap report.

Our own database in our own schema (Data/Schema.lua; SCHEMA must match ns.DATA_SCHEMA). Each source writes a layer,
`layers/<source>.json` (local, gitignored): `client` (the game's own dumps), `questie` (facts read from QuestieDB's
Forever files, used with its maintainers' permission), `wowhead` (the user-run exporter) and `learned` (positions
recorded in game). `build` merges the layers in that order, field by field — a later source overrides an earlier one
only where it has the field — and writes the tables with `src` on every record naming the layers it came from. The
`classes` table goes into one file per class, classes/<CLASS>.lua (`Signpost_Data.classes.<CLASS>`), listed in the TOC.
"""

from __future__ import annotations

import datetime as dt
import json
import re
from pathlib import Path

from .luawriter import write_lua
from .savedvars import LuaParseError, load_savedvars

SCHEMA = 1
GLOBAL = "Signpost_Data"
INTERFACE = 16001
LAYERS = ("client", "questie", "wowhead", "learned")

# table -> file, in TOC order after _meta.lua
TABLE_FILES = {
    "quests": "Quests.lua",
    "npcs": "Npcs.lua",
    "objects": "Objects.lua",
    "items": "Items.lua",
    "maps": "Maps.lua",
    "professions": "Professions.lua",
    "travel": "Travel.lua",
}
# Travel is not keyed by ID: keyed parts merge per key, list parts append.
TRAVEL_KEYED = ("flightMasters", "inns")
TRAVEL_LISTS = ("transports", "crossings")
# classes[classFile]: merged like the keyed tables, written as classes/<CLASS>.lua (PLAN §3.5/§6).
CLASSES = "classes"
CLASS_DIR = "classes"
GAP_LIST_LIMIT = 150


def header(tool: str) -> list[str]:
    return [
        f"GENERATED by Signpost/tools/{tool}; do not edit (fix the exporter and regenerate).",
        "Private data pack: never commit this file to a public repository.",
    ]


def write_toc(out_dir: Path, version: str, class_files: list[str]) -> None:
    lines = [
        f"## Interface: {INTERFACE}",
        "## Title: Signpost Data",
        "## Notes: Generated data for Signpost (private; not for redistribution).",
        "## Author: hsdevilliers",
        f"## Version: {version}",
        "## LoadOnDemand: 0",
        "## X-Generated-By: Signpost/tools/datapack.py",
        "",
        "_meta.lua",
        *TABLE_FILES.values(),
        *(f"classes\\{name}" for name in class_files),
    ]
    (out_dir / "Signpost_Data.toc").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def read_meta(out_dir: Path) -> dict | None:
    path = out_dir / "_meta.lua"
    if not path.exists():
        return None
    try:
        pack = load_savedvars(path).get(GLOBAL)
    except LuaParseError:
        return None
    meta = pack.get("_meta") if isinstance(pack, dict) else None
    return meta if isinstance(meta, dict) else None


def write_meta(out_dir: Path, meta: dict, tool: str) -> None:
    write_lua(out_dir / "_meta.lua", header(tool), [(GLOBAL, {"_meta": meta, "classes": {}})], expand_depth=3)


def write_table(out_dir: Path, table: str, value: object, tool: str) -> None:
    write_lua(out_dir / TABLE_FILES[table], header(tool), [(f"{GLOBAL}.{table}", value)])


def read_table(out_dir: Path, table: str) -> object:
    """The current contents of one generated table, or None if its file is missing."""
    path = out_dir / TABLE_FILES[table]
    if not path.exists():
        return None
    return load_savedvars(path).get(f"{GLOBAL}.{table}")


def empty_travel() -> dict:
    return {part: {} for part in TRAVEL_KEYED} | {part: [] for part in TRAVEL_LISTS}


# Layers ----------------------------------------------------------------------------------------------------------------


def layer_path(out_dir: Path, name: str) -> Path:
    return out_dir / "layers" / f"{name}.json"


def write_layer(out_dir: Path, name: str, tables: dict[str, object], origin: str, problems: list[str] = ()) -> None:
    """Store one source's records ({table: {id: record}}; travel as its parts) with where they came from."""
    if name not in LAYERS:
        raise ValueError(f"unknown layer {name!r}")
    path = layer_path(out_dir, name)
    path.parent.mkdir(parents=True, exist_ok=True)
    layer = {
        "origin": origin,
        "written": dt.date.today().isoformat(),
        "tables": tables,
        "problems": sorted(set(problems)),
    }
    path.write_text(json.dumps(layer, ensure_ascii=False, sort_keys=True), encoding="utf-8")


_DIGITS = re.compile(r"-?\d+")


def _numeric_key(key: object) -> object:
    if isinstance(key, str) and _DIGITS.fullmatch(key):
        return int(key)
    return key


def numeric_keys(value: object) -> object:
    """A copy with every digit-string dict key turned back into a number, at any depth. JSON stores keys as strings,
    and the tables are keyed by numbers inside records too (recipes by spell ID, reagents by item ID, class spells by
    level); no field name is all digits."""
    if isinstance(value, dict):
        return {_numeric_key(key): numeric_keys(item) for key, item in value.items()}
    if isinstance(value, list):
        return [numeric_keys(item) for item in value]
    return value


def read_layer(out_dir: Path, name: str) -> dict | None:
    path = layer_path(out_dir, name)
    if not path.exists():
        return None
    layer = json.loads(path.read_text(encoding="utf-8"))
    layer["tables"] = numeric_keys(layer.get("tables") or {})
    return layer


def merge_layers(layers: list[tuple[str, dict]]) -> dict[str, object]:
    """Merge layers in order: records by ID (classes by class token), field by field; `src` lists the contributing
    layers."""
    merged: dict[str, object] = {table: {} for table in TABLE_FILES}
    merged["travel"] = empty_travel()
    merged[CLASSES] = {}
    for name, layer in layers:
        for table, records in (layer.get("tables") or {}).items():
            if table == "travel":
                travel = merged["travel"]
                for part in TRAVEL_KEYED:
                    for ident, record in (records.get(part) or {}).items():
                        travel[part].setdefault(ident, {}).update(record)
                for part in TRAVEL_LISTS:
                    travel[part].extend(item for item in records.get(part) or [] if item not in travel[part])
                continue
            target_table = merged.setdefault(table, {})
            for ident, record in records.items():
                target = target_table.setdefault(ident, {})
                sources = target.get("src")
                target.update(record)
                target["src"] = name if not sources or sources == name else f"{sources},{name}"
    return merged


# Gap report ------------------------------------------------------------------------------------------------------------


def _id_list(ids: list) -> str:
    shown = ", ".join(str(i) for i in sorted(ids)[:GAP_LIST_LIMIT])
    more = len(ids) - GAP_LIST_LIMIT
    return shown + (f" (and {more} more)" if more > 0 else "")


# uiMapIDs Forever added to Classic's world (QuestieDB conversion.json "added_maps", confirmed by the client map dump).
FOREVER_ADDED_MAPS = {2482: "Mount Hyjal", 2521: "Zephras Isle", 2524: "Darkspear Islands", 2548: "Riverglades", 2652: "Shen'dralas"}


FOREVER_LAYERS_MARK = "Forever layers ("  # in the questie layer's origin when questie_import applied QuestieDB's Forever layers


def forever_gap_lines(merged: dict, layers: list[tuple[str, dict]] = ()) -> list[str]:
    """What Forever has that the pack does and does not hold: the zones it added, counted in the pack."""
    quests, npcs = merged["quests"], merged["npcs"]
    layered = any(FOREVER_LAYERS_MARK in str((layer or {}).get("origin")) for _, layer in layers)
    lines = ["## Not in this pack: Forever's own content", ""]
    if layered:
        lines += [
            "The questie layer is QuestieDB's converted Classic Era baseline (coordinates converted to Forever's maps) with "
            "QuestieDB's Forever correction layers applied on top (generated delta-base, beta traces, authored fixes; the "
            "origin line above counts the records they added and changed). Now covered: Forever-only quests, NPCs, objects "
            "and items (names, levels, who starts and ends a quest, zones, races including the Skyborne bits, classes), "
            "and the new zones' NPCs and quests that QuestieDB has. Still not covered: QuestieDB says the delta base does "
            "not supply complete objectives, restrictions or gameplay behavior, so new quests can lack objectives, chains "
            "and prerequisites; QuestieDB's Dynamic corrections (faction- and class-conditional, read at runtime) are not "
            "read; Forever's new class quests (docs/CLASS-QUESTS.md in the Signpost repository) and the new dungeons "
            "(Hall of Thanes, Ruins of Lordaeron) are only as complete as QuestieDB's records; quest XP and rewards. What "
            "the pack holds for the zones Forever added:",
            "",
        ]
    else:
        lines += [
            "The questie layer is QuestieDB's Classic Era data with the coordinates converted to Forever's maps; QuestieDB "
            "lists \"Forever race/class restrictions and new content\" as not converted. The pack is a Classic **baseline**, "
            "not Forever's database. Missing by construction: the Skyborne race (no race mask), Forever's new class quests "
            "(docs/CLASS-QUESTS.md in the Signpost repository), the new dungeons (Hall of Thanes, Ruins of Lordaeron), "
            "reworked quests and XP. What the pack holds for the zones Forever added:",
            "",
        ]
    for map_id, name in FOREVER_ADDED_MAPS.items():
        in_quests = sum(1 for q in quests.values() if q.get("zone") == map_id)
        in_npcs = sum(1 for n in npcs.values() if any(isinstance(p, list) and p and p[0] == map_id for p in n.get("p") or []))
        lines.append(f"- {name} ({map_id}): {in_quests} quests, {in_npcs} NPCs" + ("" if in_quests or in_npcs else " (nothing)"))
    return lines + [""]


def gap_report(merged: dict, layers: list[tuple[str, dict]], tool: str) -> str:
    quests, npcs, objects = merged["quests"], merged["npcs"], merged["objects"]
    no_start = [qid for qid, q in quests.items() if not q.get("s")]
    no_end = [qid for qid, q in quests.items() if not q.get("e")]
    unplaced = set()
    for q in quests.values():
        for part in ("s", "e"):
            for npc in (q.get(part) or {}).get("npc") or []:
                if not (npcs.get(npc) or {}).get("p"):
                    unplaced.add(f"npc {npc}")
            for obj in (q.get(part) or {}).get("obj") or []:
                if not (objects.get(obj) or {}).get("p"):
                    unplaced.add(f"object {obj}")
    lines = [
        "# Data gaps",
        "",
        f"Generated by `tools/{tool}` on {dt.date.today().isoformat()}. IDs and problem kinds only.",
        "",
        "Layers: " + ", ".join(f"{name} ({layer.get('origin')}, {layer.get('written')})" for name, layer in layers),
        "",
        f"Totals: {len(quests)} quests, {len(npcs)} NPCs, {len(objects)} objects, {len(merged['items'])} items, "
        f"{len(merged['maps'])} maps.",
        "",
        *forever_gap_lines(merged, layers),
        f"## Quests without a start ({len(no_start)})",
        "",
        _id_list(no_start) or "none",
        "",
        f"## Quests without an end ({len(no_end)})",
        "",
        _id_list(no_end) or "none",
        "",
        f"## Quest givers and enders without a position ({len(unplaced)})",
        "",
        _id_list(list(unplaced)) or "none",
    ]
    for name, layer in layers:
        problems = layer.get("problems") or []
        if problems:
            lines += ["", f"## Problems reported by the {name} source ({len(problems)})", ""]
            lines += [f"- {problem}" for problem in problems[:GAP_LIST_LIMIT]]
    return "\n".join(lines) + "\n"


# Build -----------------------------------------------------------------------------------------------------------------


_CLASS_TOKEN = re.compile(r"[A-Z][A-Z0-9_]*")


def write_classes(out_dir: Path, classes: dict, tool: str) -> list[str]:
    """classes/<CLASS>.lua (`Signpost_Data.classes.<CLASS> = {...}`) per class record; returns the file names, for the
    TOC. A key that is not a class token (uppercase letters, digits, _) is skipped."""
    names = []
    for class_file, record in sorted(classes.items(), key=lambda item: str(item[0])):
        if not (isinstance(class_file, str) and _CLASS_TOKEN.fullmatch(class_file)):
            continue
        folder = out_dir / CLASS_DIR
        folder.mkdir(parents=True, exist_ok=True)
        write_lua(folder / f"{class_file}.lua", header(tool), [(f"{GLOBAL}.{CLASSES}.{class_file}", record)])
        names.append(f"{class_file}.lua")
    return names


def build(out_dir: Path, tool: str) -> dict[str, int]:
    """Merge every layer into the tables, the class files, _meta.lua, the TOC and data-gaps.md. Returns the record
    count per table."""
    layers = [(name, layer) for name in LAYERS if (layer := read_layer(out_dir, name))]
    merged = merge_layers(layers)
    classes = merged.pop(CLASSES)
    for table, value in merged.items():
        write_table(out_dir, table, value, tool)
    class_files = write_classes(out_dir, classes, tool)
    counts = {table: len(value) for table, value in merged.items() if table != "travel"}
    counts["travel"] = sum(len(merged["travel"][part]) for part in (*TRAVEL_KEYED, *TRAVEL_LISTS))
    counts[CLASSES] = len(class_files)
    today = dt.date.today().isoformat()
    meta = {
        "schema": SCHEMA,
        "source": "generated" if any(counts.values()) else "stub",
        "generated": today,
        "tables": {table: {"count": count} for table, count in counts.items()},
        "layers": {name: {"origin": layer.get("origin"), "written": layer.get("written")} for name, layer in layers},
    }
    write_meta(out_dir, meta, tool)
    write_toc(out_dir, today, class_files)
    (out_dir / "data-gaps.md").write_text(gap_report(merged, layers, tool), encoding="utf-8", newline="\n")
    return counts


def init_stub(out_dir: Path, force: bool = False) -> list[Path]:
    """Write an empty pack that loads in the client and matches the schema. Refuses to replace generated data."""
    meta = read_meta(out_dir)
    if meta and meta.get("source") != "stub" and not force:
        raise RuntimeError(f"{out_dir} holds generated data (source {meta.get('source')!r}); use --force to replace it")
    out_dir.mkdir(parents=True, exist_ok=True)
    write_meta(out_dir, {"schema": SCHEMA, "source": "stub", "generated": dt.date.today().isoformat(), "tables": {}}, "datapack.py")
    for table in TABLE_FILES:
        write_table(out_dir, table, empty_travel() if table == "travel" else {}, "datapack.py")
    write_toc(out_dir, "stub", [])
    return [out_dir / "Signpost_Data.toc", out_dir / "_meta.lua", *(out_dir / name for name in TABLE_FILES.values())]
